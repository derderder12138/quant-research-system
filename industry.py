# 构建快速查找缓存
_CODE_INDUSTRY: Dict[str, str] = {}


def _build_cache():
    """构建代码→行业映射缓存。"""
    global _CODE_INDUSTRY
    if _CODE_INDUSTRY:
        return
    from stock_universe import search_stocks
    for industry, keywords in INDUSTRY_RULES.items():
        for kw in keywords:
            results = search_stocks(kw, limit=5)
            for r in results:
                if r["code"] not in _CODE_INDUSTRY:
                    _CODE_INDUSTRY[r["code"]] = industry
    # 不在任何关键词中的归类为"其他"
    # 缓存只会填充明确匹配的


def classify_stock(code: str) -> str:
    """返回单支股票的行业分类。"""
    _build_cache()
    return _CODE_INDUSTRY.get(code, "其他")


def classify_batch(codes: List[str]) -> Dict[str, str]:
    """批量分类，返回 {code: industry}。"""
    _build_cache()
    return {c: _CODE_INDUSTRY.get(c, "其他") for c in codes}


def get_industry_list() -> List[str]:
    """获取所有行业列表。"""
    return list(INDUSTRY_RULES.keys())


def get_stocks_by_industry(industry: str) -> List[str]:
    """获取某行业的所有已知股票代码。"""
    _build_cache()
    return [c for c, ind in _CODE_INDUSTRY.items() if ind == industry]


def get_industry_stats() -> Dict[str, int]:
    """各行业覆盖股票数量。"""
    _build_cache()
    stats: Dict[str, int] = {}
    for ind in _CODE_INDUSTRY.values():
        stats[ind] = stats.get(ind, 0) + 1
    return dict(sorted(stats.items(), key=lambda x: -x[1]))
